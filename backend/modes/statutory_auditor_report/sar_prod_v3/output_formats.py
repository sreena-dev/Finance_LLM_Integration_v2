"""
output_formats.py — Deterministic Display Response and Executive Summary
=============================================================================
Gap-closure Phase 4. Implements Format 1 (§2) and Format 2 (§3) of
LLM_Output_Specification_CAG_Statutory_Auditor_Report_Review.md — the
short, exception-driven, action-oriented outputs, generated by plain
Python string templating over the already-built Observation list.

WHY NO LLM CALL FOR THESE TWO FORMATS
------------------------------------------
The spec's §17 "Single Source of Truth" requirement is explicit: the
Display Response, Executive Summary and Detailed Report "should be
generated from the same structured data" so they "do not contain
different conclusions, different risk ratings or different
prioritisation." The only way to *guarantee* that — not just hope for it
— is for at least the two shorter, fully-structural formats to be built by
straight formatting of the Observation list, not by asking an LLM to
summarise it in its own words a second time (which reintroduces exactly
the risk of drift the spec is warning against). Every sentence these two
functions produce is templated from a field already on `Observation` or
`PackageContext` — nothing here is generated text.

GAP-CLOSURE PHASE 5 UPDATE — Format 3 (Detailed Review Report) now built
----------------------------------------------------------------------------
`render_detailed_report()` below builds the spec's full 16-section TOC.
13 of the 16 sections (1, 3, 4, 7-16) are deterministic templating over the
same Observation list and package data as Formats 1/2 — same "cannot
disagree" guarantee. Sections 5 and 6 (Opinion Analysis narrative, Detailed
Component Review) are NOT rebuilt as templates: they call for actual prose
synthesis (assessing whether wording is "hedged", judging whether a KAM
reads as boilerplate, etc.) that a template cannot responsibly produce, so
those two sections embed the existing LLM writer's own PART 2 output
verbatim, clearly labelled as LLM-generated narrative — a deliberate hybrid,
not a gap papered over. See GAP_CLOSURE_LOG.md, Phase 5, for the honest
limitations on this (mainly: the embedded narrative was NOT re-derived from
`observations` and so is the one place in this document where a drift
between the deterministic sections and the narrative is possible in
principle, though not observed in this phase's real-data test run).
"""

from __future__ import annotations

from dataclasses import dataclass

from sar_prod_v3.observation import Observation

_TAG_ORDER = {"FINDING": 0, "RISK_FLAG": 1, "AUDIT_POINTER": 2}
_RISK_ORDER = {"High": 0, "Medium": 1, "Low": 2, "Information request only": 3}
_TAG_DISPLAY = {"FINDING": "FINDING", "RISK_FLAG": "RISK FLAG", "AUDIT_POINTER": "AUDIT POINTER"}

_CONSISTENCY_LABELS = [
    ("FS_AR", "FS ↔ Audit Report"),
    ("FS_CARO", "FS ↔ CARO"),
    ("AR_CARO", "Audit Report ↔ CARO"),
    ("FS_AR_CARO", "FS ↔ Audit Report ↔ CARO"),
]

_CAVEAT_LINE = "AI-assisted review; subject to human audit judgement."


@dataclass
class PackageContext:
    """The package-level facts both render functions need, alongside the
    Observation list. Deliberately a small, explicit set — everything else
    a format needs should already live on an Observation."""
    entity: str
    financial_year: str
    scope: str
    opinion_type: str
    review_status: str
    review_status_reasons: list[str]


def _sort_key(obs: Observation) -> tuple:
    return (_TAG_ORDER.get(obs.tag, 9), _RISK_ORDER.get(obs.risk_rating, 9))


def _material_observations(observations: list[Observation]) -> list[Observation]:
    """Sorted most-material-first: FINDING before RISK_FLAG before
    AUDIT_POINTER, High before Medium before Low before Information-
    request-only within each tag."""
    return sorted(observations, key=_sort_key)


def _why_it_matters(obs: Observation) -> str:
    """The audit-risk / gap explanation, falling back to the observation
    text itself when neither is set. That fallback is load-bearing in
    render_display_response (§2), the one format where this is the only
    place the observation's actual content appears at all. In
    render_detailed_report (§4), `obs.observation` is already printed
    immediately beside every call site below — see `_why_it_matters_detail`
    there for the version that avoids repeating it a second time."""
    return obs.audit_risk or obs.gap or obs.observation


def _why_it_matters_detail(obs: Observation) -> str:
    """Same as `_why_it_matters`, but for contexts where `obs.observation`
    is already shown right next to this — returns "" instead of repeating
    it verbatim. Used only in render_detailed_report's §12 table/narrative,
    which used to print the identical sentence twice per observation (once
    as "Observation"/"Issue", once again as "Why It Matters") whenever
    `audit_risk`/`gap` were unset, which is the common case for
    AUDIT_POINTER/RISK_FLAG checks."""
    why = _why_it_matters(obs)
    return why if why != obs.observation else ""


def _source_label(obs: Observation) -> str:
    parts = [k.replace("_", " ").title() for k, v in obs.source.items() if v]
    if parts:
        return " / ".join(parts)
    # OTHER-classified checks (formal/applicability/pre-flight) have no
    # document-comparison bucket — fall back to the component name.
    return obs.component


def _recommended_action(obs: Observation) -> str:
    if obs.recommended_audit_action:
        return obs.recommended_audit_action[0]
    return "Raise audit query and obtain the statutory auditor's explanation."


def _overall_coherence(observations: list[Observation]) -> str:
    coherence_issues = [
        o for o in observations
        if o.sa_framework and o.sa_framework.get("opinion_coherence_issue") in ("Yes", "Requires Evidence")
    ]
    if not coherence_issues:
        return "No material opinion-coherence issues identified from the supplied package."
    high = sum(1 for o in coherence_issues if o.risk_rating == "High")
    return (
        f"{len(coherence_issues)} opinion-coherence matter(s) identified"
        f"{f' ({high} High risk)' if high else ''} — see Key Observations."
    )


def _information_limitations(ctx: PackageContext) -> str:
    if ctx.review_status == "complete":
        return "None material."
    return " ".join(ctx.review_status_reasons) or f"Review status: {ctx.review_status}."


# ---------------------------------------------------------------------------
# Format 1 — LLM Display Response (§2)
# ---------------------------------------------------------------------------

def render_display_response(ctx: PackageContext, observations: list[Observation], *, max_observations: int = 10) -> str:
    ordered = _material_observations(observations)
    high_risk_count = sum(1 for o in ordered if o.risk_rating == "High")
    key_obs = ordered[:max_observations]

    lines: list[str] = []
    lines.append(f"{ctx.entity} / {ctx.financial_year} / {ctx.scope.upper()}")
    lines.append("")
    lines.append("OVERALL REVIEW STATUS")
    lines.append(f"Opinion: {ctx.opinion_type or 'Unclear'}")
    lines.append(f"Overall coherence: {_overall_coherence(observations)}")
    lines.append(f"High-risk matters: {high_risk_count}")
    lines.append(f"Information limitations: {_information_limitations(ctx)}")
    lines.append("")

    lines.append("KEY OBSERVATIONS")
    if not key_obs:
        lines.append("No findings. No risk flags. No audit pointers.")
    for i, obs in enumerate(key_obs, 1):
        lines.append(f"{i}. [{obs.component}] — {_TAG_DISPLAY.get(obs.tag, obs.tag)}")
        lines.append(f"   Why it matters: {_why_it_matters(obs)}")
        lines.append(f"   Source: {_source_label(obs)}")
        lines.append(f"   Recommended action: {_recommended_action(obs)}")
    lines.append("")

    lines.append("CONSISTENCY ALERTS")
    for consistency_type, label in _CONSISTENCY_LABELS:
        matches = [o for o in ordered if o.consistency_type == consistency_type]
        if matches:
            summary = "; ".join(f"{o.component} ({o.risk_rating})" for o in matches[:3])
            lines.append(f"{label}: {summary}")
        else:
            lines.append(f"{label}: No material inconsistency identified.")
    lines.append("")

    lines.append("IMMEDIATE AUDIT ACTIONS")
    actions: list[str] = []
    for obs in key_obs:
        action = _recommended_action(obs)
        if action not in actions:
            actions.append(action)
        if len(actions) >= 3:
            break
    if not actions:
        lines.append("None — no material observation requires immediate follow-up.")
    else:
        for i, action in enumerate(actions, 1):
            lines.append(f"{i}. {action}")
    lines.append("")

    lines.append("CAVEAT")
    lines.append(_CAVEAT_LINE)

    return "\n".join(lines)


