# Format 2 — Executive Summary Report (§3)
# ---------------------------------------------------------------------------

def render_executive_summary(ctx: PackageContext, observations: list[Observation]) -> str:
    ordered = _material_observations(observations)
    findings_and_flags = [o for o in ordered if o.tag in ("FINDING", "RISK_FLAG")]
    silence_matters = [
        o for o in ordered
        if o.tag == "RISK_FLAG" and "silence" in (o.observation or "").lower()
    ]
    candidates_143_6 = [o for o in ordered if o.candidate_143_6]

    lines: list[str] = []
    lines.append(f"# Executive Summary — {ctx.entity} {ctx.financial_year} ({ctx.scope})")
    lines.append("")

    lines.append("## 1. Report Identification and Scope")
    lines.append(f"Entity: {ctx.entity}  |  Financial Year: {ctx.financial_year}  |  Scope: {ctx.scope}")
    lines.append("")

    lines.append("## 2. Overall Review Conclusion")
    lines.append(_overall_coherence(observations))
    lines.append(f"Review status: {ctx.review_status}.")
    if ctx.review_status != "complete":
        lines.append(" ".join(ctx.review_status_reasons))
    lines.append("")

    lines.append("## 3. Statutory Auditor Opinion Summary")
    lines.append(f"Opinion: {ctx.opinion_type or 'Unclear'}")
    lines.append("")

    lines.append("## 4. Top Findings and Risk Flags")
    if not findings_and_flags:
        lines.append("No findings. No risk flags.")
    for obs in findings_and_flags[:10]:
        lines.append(
            f"- **[{obs.observation_id}] {_TAG_DISPLAY.get(obs.tag, obs.tag)} ({obs.risk_rating})** "
            f"{obs.component} — {obs.observation}"
        )
    lines.append("")

    lines.append("## 5. FS – Audit Report – CARO Consistency Summary")
    lines.append("| Combination | Result | Observation IDs |")
    lines.append("|---|---|---|")
    for consistency_type, label in _CONSISTENCY_LABELS:
        matches = [o for o in ordered if o.consistency_type == consistency_type]
        result = "Follow-up required" if matches else "Consistent"
        ids = ", ".join(o.observation_id for o in matches) or "—"
        lines.append(f"| {label} | {result} | {ids} |")
    lines.append("")

    lines.append("## 6. Material Silence / Gap Matters")
    if not silence_matters:
        lines.append("No material silence matters identified from the supplied package.")
    for obs in silence_matters:
        lines.append(f"- [{obs.observation_id}] {obs.observation}")
    lines.append("")

    lines.append("## 7. Priority Audit Actions")
    seen_actions: list[str] = []
    for obs in findings_and_flags:
        for action in (obs.recommended_audit_action or [_recommended_action(obs)]):
            if action not in seen_actions:
                seen_actions.append(action)
    if not seen_actions:
        lines.append("None required.")
    for i, action in enumerate(seen_actions[:10], 1):
        lines.append(f"{i}. {action}")
    lines.append("")

    if candidates_143_6:
        lines.append("## 7a. Candidate Section 143(6) Matters (draft — human review required)")
        for obs in candidates_143_6:
            lines.append(f"- [{obs.observation_id}] {obs.component}: {obs.observation}")
        lines.append("")

    lines.append("## 8. Information Limitations / Caveats")
    lines.append(_information_limitations(ctx))
    lines.append(_CAVEAT_LINE)

    return "\n".join(lines)


# ---------------------------------------------------------------------------
# Format 3 — Detailed Review Report (§4-§14, 16-section TOC)
# ---------------------------------------------------------------------------

def _extract_narrative_part2(existing_report_md: str) -> str:
    """Pulls PART 2 out of the existing LLM writer's markdown (see
    PROMPT.md's REPORT_WRITER section) for embedding as sections 5/6's
    narrative. Falls back to the whole document if the marker isn't found
    (older report shape, or a failed generation) rather than returning
    nothing — a mislabelled narrative is still better than a silently
    empty section."""
    marker = "## PART 2"
    idx = (existing_report_md or "").find(marker)
    return existing_report_md[idx:] if idx != -1 else (existing_report_md or "")


def _applicability_row(applicability: dict, area: str, label: str) -> str:
    result = (applicability or {}).get(area) or {}
    status = result.get("status", "uncertain")
    basis = result.get("basis", "")
    return f"| {label} | {status} | {basis} | current assignment year | {'Verified' if status != 'uncertain' else 'Requires Verification'} |"


def render_detailed_report(
    ctx: PackageContext,
    observations: list[Observation],
    *,
    merged_json: dict,
    applicability: dict,
    quality_flags: dict,
    doc_meta: dict,
    existing_report_md: str,
) -> str:
    """Format 3 — the spec's full 16-section TOC (§5). See this module's
    docstring for which sections are deterministic vs. embedded narrative.
    """
    ordered = _material_observations(observations)
    lines: list[str] = []

    # 1. Report Control Sheet
    lines.append("# SAR Detailed Review Report")
    lines.append("")
    lines.append("## 1. Report Control Sheet")
    lines.append(f"- Entity: {ctx.entity}")
    lines.append(f"- Financial Year: {ctx.financial_year}")
    lines.append(f"- Scope: {ctx.scope}")
    lines.append(f"- Source document: {doc_meta.get('doc_name', 'Unknown')} ({doc_meta.get('total_pages', '?')} pages)")
    lines.append(f"- Review status: {ctx.review_status}")
    lines.append("- Output specification: LLM_Output_Specification_CAG_Statutory_Auditor_Report_Review.md")
    lines.append("")

    # 2. Executive Summary — a short synopsis only, not the full Format 2
    # output. This used to embed render_executive_summary()'s complete text
    # verbatim, including its own H1 title and its own nested "1."-"8."
    # numbering — which duplicated Top Findings (§4), the CARO consistency
    # table (§5) and Silence matters (§6) that this Detailed Report already
    # covers in full, later, in its own §7 (CARO consistency), §8
    # (Silence), §9 (Public-Sector) and §12 (the complete observation
    # register, both a table and a per-observation narrative block). That
    # made every C&AG-direction-style observation print 3-4 times over and
    # put a second, competing numbering scheme inside this section. §17's
    # "single source of truth" requirement is about the *data* agreeing
    # across formats, not about literally reprinting one format inside
    # another — Format 2 stays available on its own via the Executive
    # Summary tab for a reviewer who wants only that.
    lines.append("## 2. Executive Summary")
    lines.append(_overall_coherence(observations))
    lines.append(f"Opinion: {ctx.opinion_type or 'Unclear'}  |  Review status: {ctx.review_status}")
    if ctx.review_status != "complete":
        lines.append(" ".join(ctx.review_status_reasons))
    lines.append("")

    # 3. Input Package and Review Status
    lines.append("## 3. Input Package and Review Status")
    for k, v in (quality_flags or {}).items():
        lines.append(f"- {k.replace('_', ' ').title()}: {v}")
    if ctx.review_status != "complete":
        lines.append(f"- Review status reasons: {' '.join(ctx.review_status_reasons)}")
    lines.append("")

    # 4. Scope and Assignment Context
    lines.append("## 4. Scope and Assignment Context")
    lines.append(f"- Entity: {ctx.entity} | Financial Year: {ctx.financial_year} | Scope: {ctx.scope}")
    lines.append(f"- Opinion type: {ctx.opinion_type}")
    lines.append("")

    # 5 & 6 — embedded LLM narrative (see module docstring: not templated)
    lines.append("## 5-6. Statutory Auditor's Opinion Analysis and Detailed Component Review")
    lines.append("_The following is generated by the report-writer LLM from the same structured")
    lines.append("data package as the deterministic sections above and below; it is not itself")
    lines.append("templated from `observations` — see GAP_CLOSURE_LOG.md, Phase 5, for why._")
    lines.append("")
    lines.append(_extract_narrative_part2(existing_report_md))
    lines.append("")

    # 7. FS - Audit Report - CARO Consistency Analysis (§6 of the output spec)
    lines.append("## 7. FS – Audit Report – CARO Consistency Analysis")
    lines.append("| Combination | Result | Material Inconsistency | SA 700/705 Relevance | Observation ID |")
    lines.append("|---|---|---|---|---|")
    combo_matches: dict[str, list[Observation]] = {}
    for consistency_type, label in _CONSISTENCY_LABELS:
        matches = [o for o in ordered if o.consistency_type == consistency_type]
        combo_matches[consistency_type] = matches
        result = "Follow-up" if matches else "Consistent"
        sa_rel = "; ".join(sorted({o.sa_framework["standard"] for o in matches if o.sa_framework})) or "N/A"
        ids = ", ".join(o.observation_id for o in matches) or "—"
        lines.append(f"| {label} | {result} | {'Yes' if matches else 'No'} | {sa_rel} | {ids} |")
    lines.append("")
    lines.append("_Only inconsistent/material combinations are expanded below — per the output_")
    lines.append("_specification's own rule against pages of \"consistent\" results._")
    for consistency_type, label in _CONSISTENCY_LABELS:
        matches = combo_matches[consistency_type]
        if not matches:
            continue
        lines.append(f"\n**{label}:**")
        for obs in matches:
            lines.append(f"- [{obs.observation_id}] {obs.component} — {obs.observation}")
            lines.append(f"  SA 700/705 relevance: {obs.sa_framework['standard'] if obs.sa_framework else 'N/A'} | Risk: {obs.risk_rating}")
    lines.append("")

    # 8. Silence and Material Gap Analysis
    lines.append("## 8. Silence and Material Gap Analysis")
    silence_matters = [o for o in ordered if o.tag == "RISK_FLAG" and "silence" in (o.observation or "").lower() or "echo" in (o.observation or "").lower()]
    if not silence_matters:
        lines.append("No material silence matters identified from the supplied package.")
    else:
        lines.append("| FS Matter | Expected Report Location | Auditor Report Position | Significance | Recommended Action |")
        lines.append("|---|---|---|---|---|")
        for obs in silence_matters:
            action = obs.recommended_audit_action[0] if obs.recommended_audit_action else "Raise audit query."
            lines.append(f"| {obs.component} | {obs.component} | Not identified in supplied package | {obs.risk_rating} | {action} |")
    lines.append("")

    # 9. Public-Sector / High-Sensitivity Matters (conditional)
    lines.append("## 9. Public-Sector / High-Sensitivity Matters")
    ps_matters = [o for o in ordered if o.public_sector_lens]
    if not ps_matters:
        lines.append("No separately reportable public-sector sensitivity was identified from the supplied package.")
    else:
        for obs in ps_matters:
            lines.append(f"- [{obs.observation_id}] {obs.component} — nature: {obs.public_sector_lens.get('nature')}")
    lines.append("")

    # 10. Consolidated / Group Matters. Always rendered — omitting the
    # heading entirely for a standalone-scope report (the common case) used
    # to make the TOC jump straight from "9." to "12.", silently skipping
    # 10 and 11, which is exactly what looked like broken numbering. Every
    # other conditional section in this function (9, 13) keeps its heading
    # and prints a "none identified" fallback instead; this now matches.
    lines.append("## 10. Consolidated / Group Matters")
    if ctx.scope == "consolidated":
        lines.append("Group-audit-specific checks are not yet implemented in this pipeline — see GAP_CLOSURE_LOG.md.")
    else:
        lines.append(f"Not applicable — this review's scope is {ctx.scope}, not consolidated.")
    lines.append("")

    # 11. Prior-Year / Continuing Matters. Always rendered — see §10's note above.
    lines.append("## 11. Prior-Year / Continuing Matters")
    prior_matters = [o for o in ordered if o.check_id == "PRIOR-OPN-01"]
    if not prior_matters:
        lines.append("No prior-year or continuing matters were identified from the supplied package.")
    else:
        for obs in prior_matters:
            lines.append(f"- [{obs.observation_id}] {obs.observation}")
    lines.append("")

    # 12. Observations, Audit Pointers and Evidence Required (merged register)
    lines.append("## 12. Observations, Audit Pointers and Evidence Required")
    lines.append("| ID | Observation | Tag | Risk | Source | Why It Matters | Evidence / Audit Pointer | Reviewer Action |")
    lines.append("|---|---|---|---|---|---|---|---|")
    for obs in ordered:
        evidence = "; ".join(obs.evidence_required) or "—"
        lines.append(
            f"| {obs.observation_id} | {obs.observation} | {_TAG_DISPLAY.get(obs.tag, obs.tag)} | "
            f"{obs.risk_rating} | {_source_label(obs)} | {_why_it_matters_detail(obs) or '—'} | {evidence} | {obs.reviewer_status} |"
        )
    lines.append("")
    for obs in ordered:
        lines.append(f"**Observation {obs.observation_id}** (Check ID: {obs.check_id})")
        lines.append(f"- Issue: {obs.observation}")
        lines.append(f"- Classification: {_TAG_DISPLAY.get(obs.tag, obs.tag)} | Risk: {obs.risk_rating} | Confidence: {obs.confidence}")
        lines.append(f"- Source: {_source_label(obs)}")
        if obs.sa_framework:
            lines.append(f"- SA 700/705 consideration: {obs.sa_framework['standard']} ({obs.sa_framework['nature']})")
        why = _why_it_matters_detail(obs)
        if why:
            lines.append(f"- Why it matters: {why}")
        if obs.evidence_required:
            lines.append(f"- Evidence required: {'; '.join(obs.evidence_required)}")
        if obs.caveats:
            lines.append(f"- Caveats: {' '.join(obs.caveats)}")
        lines.append(f"- Reviewer decision: {obs.reviewer_status}")
        lines.append("")

    # 13. Candidate Section 143(6) Matters
    lines.append("## 13. Candidate Matters for Consideration under Section 143(6)")
    candidates = [o for o in ordered if o.candidate_143_6]
    if not candidates:
        lines.append("No observation in this review meets the threshold for a candidate section 143(6) matter (clear source trace + materiality + tag=FINDING at High risk).")
    for obs in candidates:
        lines.append(f"\n**Candidate Matter {obs.observation_id}**")
        lines.append(f"- Source established: {obs.evidence}")
        lines.append(f"- References: {_source_label(obs)}")
        lines.append(f"- Issue: {obs.observation}")
        lines.append(f"- Financial/Reporting impact: {obs.audit_risk or 'Not established from the supplied package.'}")
        lines.append(f"- Public-sector relevance: {obs.public_sector_lens or 'Not classified as public-sector-sensitive.'}")
        lines.append(f"- Evidence pending: {'; '.join(obs.evidence_required) or 'None identified.'}")
        lines.append(f"- Draft safe wording: {obs.safe_candidate_wording or '(not drafted)'}")
        lines.append("- Status: DRAFT — HUMAN REVIEW REQUIRED")
    lines.append("")

    # 14. Limitations and Caveats
    lines.append("## 14. Limitations and Caveats")
    lines.append("| Limitation | Affected Analysis | Impact | Required Action |")
    lines.append("|---|---|---|---|")
    if ctx.review_status != "complete":
        for reason in ctx.review_status_reasons:
            lines.append(f"| {reason} | Overall review | Review status: {ctx.review_status} | Resolve before relying on High-confidence observations |")
    all_caveats = {c for o in ordered for c in o.caveats}
    for caveat in all_caveats:
        lines.append(f"| {caveat} | Individual observation(s) | Confidence/tag adjusted | Verify against source |")
    lines.append("")

    # 15. Reviewer Action Summary
    lines.append("## 15. Reviewer Action Summary")
    lines.append("| Priority | Observation ID | Action | Responsible Person / Team | Evidence Required | Status |")
    lines.append("|---|---|---|---|---|---|")
    for obs in [o for o in ordered if o.tag in ("FINDING", "RISK_FLAG", "AUDIT_POINTER")]:
        action = obs.recommended_audit_action[0] if obs.recommended_audit_action else "Raise audit query."
        lines.append(
            f"| {obs.risk_rating} | {obs.observation_id} | {action} | Audit team | "
            f"{'; '.join(obs.evidence_required) or '—'} | {obs.reviewer_status} |"
        )
    lines.append("")

    # 16. Annexures
    lines.append("## 16. Annexures")
    lines.append("\n### Annexure A — Documents Reviewed and Source Index")
    lines.append("| Document ID | Document | Pages | Scope | Quality |")
    lines.append("|---|---|---|---|---|")
    lines.append(f"| {doc_meta.get('doc_id', '?')} | {doc_meta.get('doc_name', '?')} | {doc_meta.get('total_pages', '?')} | {ctx.scope} | {quality_flags.get('main_text', 'unknown')} |")

    lines.append("\n### Annexure B — Report Component Mapping")
    lines.append("| Component | Retrieval Quality |")
    lines.append("|---|---|")
    for comp, qkey in [
        ("Main Report", "main_text"), ("CARO", "caro_text"), ("IFC", "ifc_text"),
        ("Directors' Report", "dir_report"), ("Financial Statements", "fs_tables"),
    ]:
        lines.append(f"| {comp} | {quality_flags.get(qkey, 'unknown')} |")

    lines.append("\n### Annexure C — Detailed CARO Clause Status")
    lines.append("| CARO Clause | Status | Adverse / Qualified Matter | Observation ID |")
    lines.append("|---|---|---|---|")
    caro_clauses = (merged_json.get("CARO_2020") or {}).get("clauses") or []
    if not caro_clauses:
        lines.append("| — | Not extracted / not applicable | — | — |")
    for clause in caro_clauses:
        status = clause.get("answer", "unknown")
        matter = "No material inconsistency identified." if status == "clean" else (clause.get("verbatim_quote") or "")
        related = next((o.observation_id for o in ordered if clause.get("clause_no", "") in (o.check_id or "")), "—")
        lines.append(f"| ({clause.get('clause_no', '?')}) | {status} | {matter[:150]} | {related} |")

    directions_obs = [o for o in ordered if o.check_id.startswith("DIR-")]
    if directions_obs:
        lines.append("\n### Annexure D — C&AG Directions Status")
        lines.append("| Direction | Addressed | Observation ID |")
        lines.append("|---|---|---|")
        for obs in directions_obs:
            lines.append(f"| {obs.component} | {'No' if obs.tag != 'AUDIT_POINTER' else 'Partially'} | {obs.observation_id} |")

    lines.append("\n### Annexure E — Framework / Applicability Verification")
    lines.append("| Requirement | Applicability | Basis | Version / Year | Verification Status |")
    lines.append("|---|---|---|---|---|")
    lines.append(_applicability_row(applicability, "caro", "CARO"))
    lines.append(_applicability_row(applicability, "kam", "KAM"))
    lines.append(_applicability_row(applicability, "ifc", "IFC"))

    lines.append("\n### Annexure F — Machine-Readable Observation Data")
    lines.append(
        f"{len(observations)} structured observation(s) available as the `observations` field of this "
        f"pipeline's JSON output — not reproduced inline here per the output specification's own note "
        f"that this annexure need not be printed in the rendered report."
    )

    return "\n".join(lines)
